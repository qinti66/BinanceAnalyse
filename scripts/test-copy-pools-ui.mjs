import assert from "node:assert/strict";
import {mkdir,readFile} from "node:fs/promises";
import {pathToFileURL} from "node:url";
import {effectivePool} from "../lib/copy-trading/model.ts";
const {chromium}=await import(pathToFileURL(process.argv[2]).href);
const browser=await chromium.launch({channel:"msedge",headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}});
const base="http://127.0.0.1:5173",snapshot=JSON.parse(await readFile("public/copy-trading/latest.json","utf8")),errors=[],posts=[];
const counts={quality:snapshot.traders.filter(t=>effectivePool(t)==="quality").length,ordinary:snapshot.traders.filter(t=>effectivePool(t)==="ordinary").length};
page.on("pageerror",e=>errors.push(String(e)));
await mkdir("artifacts/copy-trading",{recursive:true});
await page.route("**/copy-trading/latest.json?*",route=>route.fulfill({status:200,contentType:"application/json",body:JSON.stringify(snapshot)}));
await page.route("http://127.0.0.1:8792/**",route=>{
 const req=route.request(),isUpdate=req.url().endsWith("/update");
 if(isUpdate)posts.push(JSON.parse(req.postData()).scope);
 return route.fulfill({status:isUpdate?202:200,contentType:"application/json",headers:{"Access-Control-Allow-Origin":base},body:JSON.stringify({state:isUpdate?"running":posts.length?"complete":"idle",message:isUpdate?"测试更新进行中":posts.length?"测试更新完成":"测试手动更新就绪"})});
});
try{
 await page.goto(base+"/copy-trading");await page.waitForLoadState("networkidle");
 assert.equal(await page.locator(".cp-list tbody tr").count(),counts.quality);
 assert.equal(posts.length,0,"opening page must not collect");
 await page.getByRole("tab",{name:"普通池",exact:true}).click();
 assert.equal(await page.locator(".cp-list tbody tr").count(),counts.ordinary);
 const target=snapshot.traders.find(t=>effectivePool(t)==="ordinary");
 await page.getByRole("textbox",{name:"搜索带单员"}).fill(target.id);
 await page.getByRole("button",{name:"查看 "+target.name+" 详情",exact:true}).click();
 assert.match(await page.getByRole("region",{name:"带单员详情"}).innerText(),/订单证据时间/);
 await page.getByRole("button",{name:"关注 "+target.name,exact:true}).click();
 await page.getByRole("button",{name:"取消关注 "+target.name,exact:true}).waitFor();
 await page.getByRole("combobox",{name:"优质池更新周期",exact:true}).click();
 await page.getByRole("option",{name:"每12小时",exact:true}).click();
 await page.getByRole("combobox",{name:"普通池更新周期",exact:true}).click();
 await page.getByRole("option",{name:"每周",exact:true}).click();
 assert.equal(posts.length,0,"changing a saved interval must not start collection");
 await page.reload();await page.waitForLoadState("networkidle");
 assert.match(await page.getByRole("combobox",{name:"优质池更新周期",exact:true}).innerText(),/每12小时/);
 assert.match(await page.getByRole("combobox",{name:"普通池更新周期",exact:true}).innerText(),/每周/);
 await page.getByRole("tab",{name:"普通池",exact:true}).click();
 await page.getByRole("combobox",{name:"筛选标记",exact:true}).click();
 await page.getByRole("option",{name:"我的关注",exact:true}).click();
 assert.equal(await page.locator(".cp-list tbody tr").count(),1);
 await page.getByRole("button",{name:"取消关注 "+target.name,exact:true}).click();
 assert.equal(await page.locator(".cp-list tbody tr").count(),0);
 await page.getByRole("button",{name:"查看普通池",exact:true}).click();
 assert.equal(await page.locator(".cp-list tbody tr").count(),counts.ordinary);
 await page.getByRole("combobox",{name:"排序",exact:true}).click();await page.getByRole("option",{name:"持仓中位数",exact:true}).click();
 const sorted=snapshot.traders.filter(t=>effectivePool(t)==="ordinary").sort((a,b)=>(b.metrics.medianHoldSeconds??-1)-(a.metrics.medianHoldSeconds??-1));
 assert.ok((await page.locator(".cp-list tbody tr").first().innerText()).includes(sorted[0].name));
 const scopes=[["更新普通池","ordinary"],["更新两个池","all"]];
 if(counts.quality>0)scopes.unshift(["更新优质池","quality"]);
 for(const [name,scope] of scopes){
  await page.getByRole("button",{name,exact:true}).click();
  await page.getByRole("status").filter({hasText:"测试更新完成"}).waitFor({timeout:10000});
  assert.equal(posts.at(-1),scope);
 }
 await page.route("**/copy-trading/latest.json?*",route=>route.fulfill({status:503,body:"offline"}));
 await page.getByRole("button",{name:"读取保存快照",exact:true}).click();await page.getByRole("alert").waitFor();
 assert.equal(await page.locator(".cp-list tbody tr").count(),counts.ordinary,"failed refresh retains data");
 await page.unroute("**/copy-trading/latest.json?*");
 await page.getByRole("button",{name:"读取保存快照",exact:true}).click();await page.getByRole("alert").waitFor({state:"hidden"});
 await page.getByRole("combobox",{name:"排序",exact:true}).click();await page.getByRole("option",{name:"质量门槛通过率",exact:true}).click();
 await page.getByRole("listbox").waitFor({state:"hidden"});
 await page.screenshot({path:"artifacts/copy-trading/desktop.png",fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:"artifacts/copy-trading/mobile.png",fullPage:false});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"mobile body overflow");
 assert.deepEqual(errors,[]);
 await page.setViewportSize({width:1440,height:1080});await page.getByRole("tab",{name:"优质池",exact:true}).click();
 await page.screenshot({path:"artifacts/copy-trading/quality.png",fullPage:false});
 const forbidden=await fetch("http://127.0.0.1:8792/update",{method:"POST",headers:{Origin:"https://outside.example","Content-Type":"application/json"},body:'{"scope":"all"}'});
 assert.equal(forbidden.status,403);
 const bad=await fetch("http://127.0.0.1:8792/update",{method:"POST",headers:{Origin:base,"Content-Type":"application/json"},body:'{"scope":"run-shell"}'});
 assert.equal(bad.status,400);
 assert.equal((await (await fetch("http://127.0.0.1:8792/status")).json()).state,"idle");
 console.log(JSON.stringify({passed:true,counts,pageErrors:errors.length,savedPreferences:true,automaticCollection:false,testedScopes:posts}));
}finally{await browser.close();}
