import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser=await chromium.launch({channel:"msedge",headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];page.on("pageerror",e=>errors.push(String(e)));
const base="http://127.0.0.1:5173";
const snapshot=await (await fetch(base+"/indicators/latest.json")).json();
await mkdir("artifacts/indicators",{recursive:true});
try{
 await page.goto(base+"/indicators");await page.waitForLoadState("networkidle");
 await page.getByRole("button",{name:"查看 0G 指标",exact:true}).waitFor();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coverage.candidates);
 await page.screenshot({path:"artifacts/indicators/desktop.png",fullPage:false});
 await page.getByRole("tab",{name:"全部代币",exact:true}).click();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coverage.tokens);
 await page.getByRole("textbox",{name:"搜索币种"}).fill("BTC");
 await page.getByRole("button",{name:"查看 BTC 指标",exact:true}).click();
 assert.match(await page.locator(".im-detail").innerText(),/BTC \/ 数据证据/);
 await page.locator(".im-contracts summary").click();
 assert.equal(await page.locator(".im-contracts tbody tr").count(),snapshot.coins.find(c=>c.token==="BTC").contractCount);
 await page.getByRole("textbox",{name:"搜索币种"}).fill("IMPOSSIBLECOIN");
 await page.getByRole("button",{name:"查看全部代币",exact:true}).click();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coverage.tokens);
 await page.getByRole("combobox",{name:"筛选信号",exact:true}).click();
 await page.getByRole("option",{name:"主动净流入",exact:true}).click();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coins.filter(c=>c.tags.includes("主动净流入")).length);
 await page.getByRole("combobox",{name:"排序依据",exact:true}).click();
 await page.getByRole("option",{name:"4h IO 净流入",exact:true}).click();
 await page.getByRole("button",{name:"切换排序方向"}).click();
 const expected=snapshot.coins.filter(c=>c.tags.includes("主动净流入")).sort((a,b)=>a.flows.h4.net-b.flows.h4.net)[0].token;
 assert.match(await page.locator(".im-list tbody tr").first().innerText(),new RegExp("^"+expected+" "));
 await page.getByRole("combobox",{name:"筛选信号",exact:true}).click();await page.getByRole("option",{name:"全部信号",exact:true}).click();
 await page.getByRole("tab",{name:"风险提示",exact:true}).click();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coins.filter(c=>c.warnings.length).length);
 await page.getByRole("tab",{name:"数据不足",exact:true}).click();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coins.filter(c=>!c.quality).length);
 await page.route("**/indicators/latest.json?*",route=>route.fulfill({status:503,body:"unavailable"}));
 await page.getByRole("button",{name:"读取已保存快照",exact:true}).click();await page.getByRole("alert").waitFor();
 assert.equal(await page.locator(".im-list tbody tr").count(),snapshot.coins.filter(c=>!c.quality).length);
 await page.unroute("**/indicators/latest.json?*");
 let posts=0;
 await page.route("http://127.0.0.1:8791/**",route=>{
   const update=route.request().url().endsWith("/update");if(update)posts++;
   return route.fulfill({status:update?202:200,contentType:"application/json",headers:{"Access-Control-Allow-Origin":base},body:JSON.stringify({state:update?"running":"complete",message:update?"测试采集进行中":"测试更新完成"})});
 });
 await page.getByRole("button",{name:"更新指标数据",exact:true}).click();
 await page.getByRole("button",{name:"采集进行中…",exact:true}).waitFor();
 await page.getByRole("status").filter({hasText:"测试更新完成"}).waitFor({timeout:10000});
 assert.equal(posts,1);
 await page.getByRole("tab",{name:"观察名单",exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:"artifacts/indicators/mobile.png",fullPage:false});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),"document must not overflow mobile viewport");
 assert.deepEqual(errors,[]);
 const forbidden=await fetch("http://127.0.0.1:8791/update",{method:"POST",headers:{Origin:"https://untrusted.example","Content-Type":"application/json"},body:"{}"});
 assert.equal(forbidden.status,403);
 assert.equal((await (await fetch("http://127.0.0.1:8791/status")).json()).state,"idle");
 console.log(JSON.stringify({passed:true,tokens:snapshot.coverage.tokens,candidates:snapshot.coverage.candidates,pageErrors:errors.length,realCollectionNotTriggered:true}));
}finally{await browser.close();}
